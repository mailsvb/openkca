var oidInvalidityDate = asn1.ObjectIdentifier{2, 5, 29, 24}

// RevocationRow is a revocation to store. InvalDate zero = none.
type RevocationRow struct {
	Serial    string
	Date      time.Time
	InvalDate time.Time
	Reason    int
}

// touchCertsWithSerial marks the CA's certificates with a serial as
// changed, so that the snapshot reloads their revocation state.
func (t *Tx) touchCertsWithSerial(ctx context.Context, caID int64, serial string) error {
	rows, err := t.QueryContext(ctx, "SELECT item FROM certs WHERE issuer=? AND serial=?", caID, serial)
	if err != nil {
		return err
	}
	var ids []int64
	for rows.Next() {
		var id int64
		rows.Scan(&id)
		ids = append(ids, id)
	}
	rows.Close()
	for _, id := range ids {
		t.Touch(id)
	}
	t.Touch(caID)
	return nil
}

// ErrUnknownCert means a revocation names a serial for which the CA has
// issued no certificate in the database (live or in the trash).
var ErrUnknownCert = errors.New("no certificate with this serial number from this CA is in the database")

// certExpiry returns the expiry of the certificate with serial issued
// under CA caID's name (live or in the trash), or ErrUnknownCert.
func (t *Tx) certExpiry(ctx context.Context, caID int64, serial string) (string, error) {
	var exp sql.NullString
	err := t.QueryRowContext(ctx, `SELECT MAX(c.not_after) FROM certs c
		WHERE c.serial=? AND c.issuer_name=(SELECT ca.subject FROM certs ca WHERE ca.item=?)`, serial, caID).Scan(&exp)
	if err != nil {
		return "", err
	}
	if !exp.Valid {
		return "", ErrUnknownCert
	}
	return exp.String, nil
}

// Revoke adds or replaces the revocation of serial under CA caID. The
// certificate must be in the database (live or in the trash); its expiry
// is recorded with the revocation, so that the entry stays on the CRL
// until CRLGrace after it even once the certificate is purged. A replaced
// entry keeps its revocation date and CRL number.
func (t *Tx) Revoke(ctx context.Context, caID int64, r RevocationRow) error {
	expires, err := t.certExpiry(ctx, caID, r.Serial)
	if err != nil {
		return err
	}
	date := fmtTime(r.Date)
	var old string
	err = t.QueryRowContext(ctx, "SELECT date FROM revocations WHERE ca=? AND serial=?", caID, r.Serial).Scan(&old)
	switch {
	case errors.Is(err, sql.ErrNoRows):
	case err != nil:
		return err
	default:
		date = old
	}
	if _, err := t.ExecContext(ctx, `INSERT INTO revocations (ca, serial, date, invalidity, reason, expires) VALUES (?, ?, ?, ?, ?, ?)
		ON CONFLICT (ca, serial) DO UPDATE SET invalidity=excluded.invalidity, reason=excluded.reason, expires=excluded.expires`,
		caID, r.Serial, date, optTime(r.InvalDate), r.Reason, expires); err != nil {
		return err
	}
	return t.touchCertsWithSerial(ctx, caID, r.Serial)
}

// Unrevoke removes a revocation.
func (t *Tx) Unrevoke(ctx context.Context, caID int64, serial string) error {
	if _, err := t.ExecContext(ctx, "DELETE FROM revocations WHERE ca=? AND serial=?", caID, serial); err != nil {
		return err
	}
	return t.touchCertsWithSerial(ctx, caID, serial)
}

// SetCAProperties updates a CA's CRL interval and default template.
func (t *Tx) SetCAProperties(ctx context.Context, caID int64, crlDays int, templateID int64) error {
	var tmplID sql.NullInt64
	if templateID != 0 {
		tmplID = sql.NullInt64{Int64: templateID, Valid: true}
	}
	res, err := t.ExecContext(ctx, "UPDATE authorities SET crl_days=?, template=? WHERE cert=?", crlDays, tmplID, caID)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n != 1 {
		return fmt.Errorf("item %d is not a CA", caID)
	}
	t.Touch(caID)
	return nil
}

// NewCRL is a generated revocation list to store.
type NewCRL struct {
	Name     string
	Source   int
	DER      []byte
	CAID     int64
	Number   int64 // 0 = no CRL number
	NextTime time.Time
}

// InsertCRL stores a CRL generated by CA n.CAID and keeps the CA's
// bookkeeping: CRL number and next update, and the CRL number on
// revocations that were not on a CRL yet. The new CRL replaces the CA's
// previously generated ones that are not in the trash; imported CRLs stay.
// It returns the new ID and how many CRLs it replaced.
func (t *Tx) InsertCRL(ctx context.Context, n NewCRL) (int64, int, error) {
	id, err := t.insertCRL(ctx, n)
	if err != nil {
		return 0, 0, err
	}
	res, err := t.ExecContext(ctx, `DELETE FROM items WHERE id<>? AND type='crl' AND source=? AND trashed IS NULL
		AND id IN (SELECT item FROM crls WHERE issuer=?)`, id, SourceName(SourceGenerated), n.CAID)
	if err != nil {
		return 0, 0, err
	}
	replaced, _ := res.RowsAffected()
	return id, int(replaced), nil
}

func (t *Tx) insertCRL(ctx context.Context, n NewCRL) (int64, error) {
	l, err := x509.ParseRevocationList(n.DER)
	if err != nil {
		return 0, err
	}
	if n.Number != 0 {
		if _, err := t.ExecContext(ctx, "UPDATE authorities SET crl_number=?, crl_next=? WHERE cert=?", n.Number, optTime(n.NextTime), n.CAID); err != nil {
			return 0, err
		}
	} else if _, err := t.ExecContext(ctx, "UPDATE authorities SET crl_next=? WHERE cert=?", optTime(n.NextTime), n.CAID); err != nil {
		return 0, err
	}
	t.Touch(n.CAID)
	if _, err := t.ExecContext(ctx, "UPDATE revocations SET crl_number=? WHERE crl_number IS NULL AND ca=?", n.Number, n.CAID); err != nil {
		return 0, err
	}
	id, err := t.insertItem(ctx, n.Name, TypeCRL, n.Source, "")
	if err != nil {
		return 0, err
	}
	_, err = t.ExecContext(ctx, "INSERT INTO crls (item, der, fingerprint, issuer_name, issuer, number) VALUES (?, ?, ?, ?, ?, ?)",
		id, n.DER, Fingerprint(n.DER), l.RawIssuer, n.CAID, n.Number)
	return id, err
}

// InsertImportedCRL stores a CRL from a file: its issuer is the live CA
// certificate with the CRL's issuer name whose key verifies it, and the
// CA's revocation list is extended by the CRL's entries it does not have
// yet, for certificates in the database only (live or in the trash). It
// returns the new ID and the issuer (0 when unknown).
func (t *Tx) InsertImportedCRL(ctx context.Context, name, comment string, der []byte) (int64, int64, error) {
	l, err := x509.ParseRevocationList(der)
	if err != nil {
		return 0, 0, err
	}
	cands, err := t.certsWhere(ctx, "c.ca=1 AND c.subject=?", l.RawIssuer)
	if err != nil {
		return 0, 0, err
	}
	var issuer sql.NullInt64
	for _, strict := range []bool{true, false} {
		for _, c := range cands {
			if (!strict || mayIssueCRLs(c.cert)) && bytes.Equal(c.cert.RawSubject, l.RawIssuer) && pki.CheckCRLSignature(c.cert, l) == nil {
				issuer = sql.NullInt64{Int64: c.id, Valid: true}
				break
			}
		}
		if issuer.Valid {
			break
		}
	}
	var num int64
	if l.Number != nil && l.Number.IsInt64() {
		num = l.Number.Int64()
	}
	id, err := t.insertItem(ctx, name, TypeCRL, SourceImported, comment)
	if err != nil {
		return 0, 0, err
	}
	if _, err := t.ExecContext(ctx, "INSERT INTO crls (item, der, fingerprint, issuer_name, issuer, number) VALUES (?, ?, ?, ?, ?, ?)",
		id, der, Fingerprint(der), l.RawIssuer, issuer, num); err != nil {
		return 0, 0, err
	}
	if !issuer.Valid {
		return id, 0, nil
	}
	for _, e := range l.RevokedCertificateEntries {
		serial := SerialHex(e.SerialNumber)
		var inval time.Time
		for _, x := range e.Extensions {
			if x.Id.Equal(oidInvalidityDate) {
				asn1.UnmarshalWithParams(x.Value, &inval, "generalized")
			}
		}
		expires, err := t.certExpiry(ctx, issuer.Int64, serial)
		if errors.Is(err, ErrUnknownCert) {
			continue // a certificate this database does not know
		}
		if err != nil {
			return 0, 0, err
		}
		res, err := t.ExecContext(ctx, `INSERT INTO revocations (ca, serial, date, invalidity, reason, expires) VALUES (?, ?, ?, ?, ?, ?)
			ON CONFLICT (ca, serial) DO NOTHING`, issuer.Int64, serial, fmtTime(e.RevocationTime), optTime(inval), e.ReasonCode, expires)
		if err != nil {
			return 0, 0, err
		}
		if n, _ := res.RowsAffected(); n > 0 {
			if err := t.touchCertsWithSerial(ctx, issuer.Int64, serial); err != nil {
				return 0, 0, err
			}
		}
	}
	return id, issuer.Int64, nil
}

// mayIssueCRLs applies the CA and key usage rules of crypto/x509's
// RevocationList.CheckSignatureFrom.
func mayIssueCRLs(c *x509.Certificate) bool {
	if c.Version == 3 && !c.BasicConstraintsValid || c.BasicConstraintsValid && !c.IsCA {
		return false
	}
	return c.KeyUsage == 0 || c.KeyUsage&x509.KeyUsageCRLSign != 0
}
