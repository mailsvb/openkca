package xdb

import (
	"context"
	"crypto/x509"
	"database/sql"
	"fmt"
	"time"
)

// RevocationRow is a revocation to store. InvalDate zero = undefined.
type RevocationRow struct {
	Serial    string
	Date      time.Time
	InvalDate time.Time
	Reason    int
}

func plainTime(t time.Time) string {
	if t.IsZero() || t.Year() >= 9999 {
		return UndefinedTime
	}
	return t.UTC().Format(TimeLayout)
}

// touchCertsWithSerial marks the CA's certificates with a serial as
// changed, so that the snapshot reloads their revocation state.
func (t *Tx) touchCertsWithSerial(ctx context.Context, caID int64, serial string) error {
	rows, err := t.QueryContext(ctx, "SELECT item FROM certs WHERE issuer=? AND serial=?", caID, serial)
	if err != nil {
		return err
	}
	var ids []int64
	for rows.Next() {
		var id int64
		rows.Scan(&id)
		ids = append(ids, id)
	}
	rows.Close()
	for _, id := range ids {
		t.Touch(id)
	}
	t.Touch(caID)
	return nil
}

// Revoke adds or replaces the revocation of serial under CA caID. A
// replaced entry keeps its revocation date and CRL number, as XCA's
// revocation editor does.
func (t *Tx) Revoke(ctx context.Context, caID int64, r RevocationRow) error {
	var date string
	var crlNo sql.NullInt64
	err := t.QueryRowContext(ctx, "SELECT date, crlNo FROM revocations WHERE caId=? AND serial=?", caID, r.Serial).Scan(&date, &crlNo)
	switch {
	case err == sql.ErrNoRows:
		date = plainTime(r.Date)
	case err != nil:
		return err
	default:
		if _, err := t.ExecContext(ctx, "DELETE FROM revocations WHERE caId=? AND serial=?", caID, r.Serial); err != nil {
			return err
		}
	}
	if _, err := t.ExecContext(ctx, "INSERT INTO revocations (caId, serial, date, invaldate, crlNo, reasonBit) VALUES (?, ?, ?, ?, ?, ?)",
		caID, r.Serial, date, plainTime(r.InvalDate), crlNo, r.Reason); err != nil {
		return err
	}
	return t.touchCertsWithSerial(ctx, caID, r.Serial)
}

// Unrevoke removes a revocation.
func (t *Tx) Unrevoke(ctx context.Context, caID int64, serial string) error {
	if _, err := t.ExecContext(ctx, "DELETE FROM revocations WHERE caId=? AND serial=?", caID, serial); err != nil {
		return err
	}
	return t.touchCertsWithSerial(ctx, caID, serial)
}

// SetCAProperties updates authority.crlDays and authority.template.
func (t *Tx) SetCAProperties(ctx context.Context, caID int64, crlDays int, templateID int64) error {
	var tmpl sql.NullInt64
	if templateID != 0 {
		tmpl = sql.NullInt64{Int64: templateID, Valid: true}
	}
	res, err := t.ExecContext(ctx, "UPDATE authority SET crlDays=?, template=? WHERE item=?", crlDays, tmpl, caID)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n != 1 {
		return fmt.Errorf("item %d is not a CA", caID)
	}
	t.Touch(caID)
	return nil
}

// NewCRL is a generated revocation list to store.
type NewCRL struct {
	Name     string
	Source   int
	DER      []byte
	CAID     int64
	Number   int64 // 0 = no CRL number
	NextTime time.Time
}

// InsertCRL stores a CRL generated by CA n.CAID and does XCA's bookkeeping
// (db_crl::newCrl): authority.crlNo and crlExpire, and the CRL number on
// revocations that were not on a CRL yet.
func (t *Tx) InsertCRL(ctx context.Context, n NewCRL) (int64, error) {
	l, err := x509.ParseRevocationList(n.DER)
	if err != nil {
		return 0, err
	}
	if n.Number != 0 {
		if _, err := t.ExecContext(ctx, "UPDATE authority SET crlNo=?, crlExpire=? WHERE item=?", n.Number, plainTime(n.NextTime), n.CAID); err != nil {
			return 0, err
		}
	} else if _, err := t.ExecContext(ctx, "UPDATE authority SET crlExpire=? WHERE item=?", plainTime(n.NextTime), n.CAID); err != nil {
		return 0, err
	}
	t.Touch(n.CAID)
	if _, err := t.ExecContext(ctx, "UPDATE revocations SET crlNo=? WHERE crlNo IS NULL AND caId=?", n.Number, n.CAID); err != nil {
		return 0, err
	}
	id, err := t.insertItem(ctx, n.Name, TypeCRL, n.Source, "")
	if err != nil {
		return 0, err
	}
	issHash, err := NameHash(l.RawIssuer)
	if err != nil {
		return 0, err
	}
	_, err = t.ExecContext(ctx, "INSERT INTO crls (item, hash, num, iss_hash, issuer, crl) VALUES (?, ?, ?, ?, ?, ?)",
		id, Hash(n.DER), n.Number, issHash, n.CAID, b64enc(n.DER))
	return id, err
}
